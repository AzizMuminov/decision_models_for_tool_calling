def rows(p: Path):
    return [json.loads(l) for l in open(p)]


def paired(a: list[bool], b: list[bool], seed: int = 0) -> dict:
    """a, b: per-item correctness of two systems on the same items. Difference is a - b."""
    a_, b_ = np.asarray(a, float), np.asarray(b, float)
    d = a_ - b_
    rng = np.random.default_rng(seed)
    bs = d[rng.integers(0, len(d), size=(B, len(d)))].mean(1)
    t = mcnemar(b, a)  # mcnemar's a_only counts items only its first argument (b) got right
    return {"n": len(d), "a": float(a_.mean()), "b": float(b_.mean()), "a_only": t["b_only"], "b_only": t["a_only"],
            "diff": float(d.mean()), "lo": float(np.quantile(bs, 0.025)), "hi": float(np.quantile(bs, 0.975)), "p": t["p_value"]}


def fmt(r: dict) -> str:
    return (f"{r['n']} | {r['a']:.3f} | {r['b']:.3f} | {r['a_only']}/{r['b_only']} | "
            f"{100 * r['diff']:+.1f} [{100 * r['lo']:+.1f}, {100 * r['hi']:+.1f}] | {r['p']:.2g}")


HDR = "| comparison (A vs B) | n | A | B | only A right / only B right | A−B, pts [95% CI] | McNemar p |"
SEP = "|---|---|---|---|---|---|---|"

# ---------------------------------------------------------------- 1a. Study 2: Sonnet subset
H = ROOT / "results/holster_v1"


def holster_ok(name: str) -> dict:
    out = {}
    for r in rows(H / f"{name}.jsonl"):
        if r["src"] != "bfcl_pad" or not r["should_call"]:
            continue
        if r["system"] == "dm" or name.startswith("lexical"):
            ok = r["select_ok"]
        else:
            ok = bool(r["calls"]) and sorted(next(iter(c)) for c in r["calls"]) == r["gold_tools"]
        out[r["id"]] = bool(ok)
    return out


S2 = {n: holster_ok(f) for n, f in (("MSD1", "dm__msd1"), ("Jev", "dm__jev"), ("DeepSeek", "llm_native__deepseek"),
                                    ("Sonnet", "llm_native__sonnet"))}
L += ["## 1. Paired effect sizes", "", "### Study 2, selection on padded BFCL (should-call items)", "", HDR, SEP]
J["study2"] = {}
for K in (25, 100, 200):
    for a, b in (("MSD1", "DeepSeek"), ("Jev", "DeepSeek"), ("MSD1", "Sonnet"), ("Jev", "Sonnet")):
        ids = sorted(i for i in set(S2[a]) & set(S2[b]) if i.endswith(f"@K{K}"))
        if not ids:
            continue
        r = paired([S2[a][i] for i in ids], [S2[b][i] for i in ids])
        J["study2"][f"{a}_vs_{b}@{K}"] = r
        L.append(f"| {a} vs {b}, K={K} | {fmt(r)} |")

