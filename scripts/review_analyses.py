# ---------------------------------------------------------------- 3 + 4. Study 1: judge and held-out tau
R1 = ROOT / "results/openrouter_v1"
cache_p = OUT / "when2call_rejudge_cache.jsonl"
sol = {json.loads(l)["key"]: json.loads(l)["label"] for l in open(cache_p)} if cache_p.exists() else {}


def key(r: dict) -> str:
    return hashlib.sha1(f"{r['id']}\n{r['text']}".encode()).hexdigest()


def correct(r: dict, judge: str) -> bool:
    if r["benchmark"] == "when2call" and r["judge_used"] and judge == "sol":
        return sol[key(r)] == r["gold_label"]
    return bool(r["correct"])


def load1(bench: str, cond: str, llm: str, dm: str) -> dict:
    out = {}
    for f in R1.glob(f"{bench}__*__{cond}__{llm}__{dm}.jsonl"):
        for r in rows(f):
            out[(r["benchmark"], r["id"])] = r
    return out


judged = [r for f in R1.glob("when2call__*.jsonl") for r in rows(f) if r["judge_used"]]
if sol and all(key(r) in sol for r in judged):
    pairs = [(r["pred_label"], sol[key(r)]) for r in judged]
    agree = np.mean([a == b for a, b in pairs])
    labs = ["direct", "request_for_info", "cannot_answer"]
    po = agree
    pa = Counter(a for a, _ in pairs)
    pb = Counter(b for _, b in pairs)
    pe = sum(pa[l] * pb[l] for l in labs) / len(pairs) ** 2
    kappa = (po - pe) / (1 - pe)
    cm = Counter(pairs)
    J["judge"] = {"n": len(pairs), "agreement": float(agree), "kappa": float(kappa),
                  "confusion": {f"{a}->{b}": v for (a, b), v in cm.items()}}
    L += ["## 3. Judge sensitivity (Study 1, When2Call text replies)", "",
          f"{len(pairs)} judged replies (all conditions). DeepSeek vs GPT-6.1 Sol: agreement {agree:.3f}, "
          f"Cohen's κ {kappa:.3f}.", "", "| DeepSeek label → Sol label | count |", "|---|---|"]
    L += [f"| {a} → {b} | {v} |" for (a, b), v in sorted(cm.items())]
    L += ["", "When2Call accuracy under each judge (rows with a tool call or a closed gate are unaffected):", "",
          "| condition | LLM | DM | judge=DeepSeek | judge=Sol | cannot_answer D/S | request_for_info D/S |",
          "|---|---|---|---|---|---|---|"]
    J["judge"]["table"] = {}
    for cond, llm, dm in (("llm_native", "deepseek", "-"), ("llm_native", "sonnet", "-"), ("dm_gate", "deepseek", "msd1"),
                          ("dm_gate", "sonnet", "msd1"), ("dm_gate", "deepseek", "jev"), ("dm_gate", "sonnet", "jev"),
                          ("dm_select", "deepseek", "msd1"), ("dm_select", "sonnet", "msd1"),
                          ("oracle_select", "deepseek", "-"), ("oracle_select", "sonnet", "-")):
        rs = list(load1("when2call", cond, llm, dm).values())
        acc = {j: np.mean([correct(r, j) for r in rs]) for j in ("deepseek", "sol")}
        per = {l: {j: np.mean([correct(r, j) for r in rs if r["gold_label"] == l]) for j in ("deepseek", "sol")}
               for l in ("cannot_answer", "request_for_info")}
        J["judge"]["table"][f"{cond}/{llm}/{dm}"] = {"deepseek": float(acc["deepseek"]), "sol": float(acc["sol"]),
                                                       **{l: {j: float(v) for j, v in d.items()} for l, d in per.items()}}
        L.append(f"| {cond} | {llm} | {dm} | {acc['deepseek']:.3f} | {acc['sol']:.3f} | " +
                 " | ".join(f"{per[l]['deepseek']:.2f}/{per[l]['sol']:.2f}" for l in ("cannot_answer", "request_for_info")) + " |")
    judges = ("deepseek", "sol")
else:
    L += ["## 3. Judge sensitivity", "", "(re-judge cache incomplete; run scripts/rejudge_when2call.py)"]
    judges = ("deepseek",)

GRID = np.round(np.arange(0.05, 0.96, 0.05), 2)


def tau_setup(llm: str, dm: str, judge: str):
    nat = {**load1("bfcl", "llm_native", llm, "-"), **load1("when2call", "llm_native", llm, "-")}
    g = {**load1("bfcl", "dm_gate", llm, dm), **load1("when2call", "dm_gate", llm, dm)}
    ids = sorted(set(nat) & set(g))
    p = np.array([g[i]["p_tool_call"] for i in ids])
    base = np.array([correct(nat[i], judge) for i in ids], float)
    gate_open = np.array([correct(g[i], judge) for i in ids], float)  # the actual dm_gate run (open iff p >= 0.5)

    def closed_ok(r):
        if r["benchmark"] == "bfcl":
            return not r["should_call"]
        pr = {k: v for k, v in r["decision_probs"].items() if k != "tool_call"}
        return max(pr, key=pr.get) == r["gold_label"]

    clo = np.array([closed_ok(g[i]) for i in ids], float)
    # tau < 0.5 opens extra items; the LLM then sees exactly the llm_native prompt, so its llm_native output is used
    acc = np.array([np.where(p >= 0.5, gate_open, np.where(p >= t, base, clo)) if t < 0.5 else
                    np.where(p >= t, gate_open, clo) for t in GRID])
    bench = np.array([i[0] for i in ids])
    return ids, acc, base, bench


L += ["", "## 4. Held-out τ (scripted protocol)", "",
      "Protocol: τ grid 0.05–0.95 step 0.05; pooled BFCL + When2Call items; choose τ maximising accuracy on the dev "
      "items, report accuracy gain over `llm_native` on the remaining items; 200 random splits (seed 0). When the gate "
      "is open at τ ≥ 0.5 the logged `dm_gate` run is used; items opened only by τ < 0.5 use the LLM's `llm_native` "
      "output (identical prompt).", ""]
J["tau"] = {}
for judge in judges:
    L += [f"### judge = {judge}", "", "| pairing | dev = half: gain, pts [95% range] | chosen τ (IQR) | "
          "dev n=25 | n=50 | n=100 | n=200 |", "|---|---|---|---|---|---|---|"]
    for llm in ("deepseek", "sonnet"):
        for dm in ("msd1", "jev"):
            ids, acc, base, bench = tau_setup(llm, dm, judge)
            N = len(ids)
            out = {}
            for nd in (25, 50, 100, 200, N // 2):
                rng = np.random.default_rng(0)
                gains, ch = [], []
                for _ in range(200):
                    m = rng.permutation(N)
                    a, b = m[:nd], m[nd:]
                    t = acc[:, a].mean(1).argmax()
                    gains.append(acc[t, b].mean() - base[b].mean())
                    ch.append(GRID[t])
                out[nd] = {"gain": float(np.mean(gains)), "lo": float(np.quantile(gains, .025)),
                           "hi": float(np.quantile(gains, .975)), "tau_q": [float(x) for x in np.quantile(ch, [.25, .5, .75])]}
            h = out[N // 2]
            J["tau"][f"{judge}/{llm}/{dm}"] = {"n": N, **{str(k): v for k, v in out.items()}}
            L.append(f"| {llm} + {dm} | {100 * h['gain']:+.1f} [{100 * h['lo']:+.1f}, {100 * h['hi']:+.1f}] | "
                     f"{h['tau_q'][1]:.2f} ({h['tau_q'][0]:.2f}–{h['tau_q'][2]:.2f}) | " +
                     " | ".join(f"{100 * out[k]['gain']:+.1f} [{100 * out[k]['lo']:+.1f}, {100 * out[k]['hi']:+.1f}]"
                                for k in (25, 50, 100, 200)) + " |")
    L.append("")
# one fixed dev split, headline rows at the tau it picks
ids, acc, base, bench = tau_setup("deepseek", "msd1", "deepseek")
m = np.random.default_rng(12345).permutation(len(ids))
dev, test = m[: len(ids) // 2], m[len(ids) // 2:]
J["fixed_split"] = {}
L += ["### One fixed dev/test split (seed 12345, 50/50); τ picked on dev, accuracy on test", "",
      "| pairing | τ | BFCL test: native → gated | When2Call test: native → gated |", "|---|---|---|---|"]
for llm in ("deepseek", "sonnet"):
    for dm in ("msd1", "jev"):
        ids, acc, base, bench = tau_setup(llm, dm, "deepseek")
        t = acc[:, dev].mean(1).argmax()
        cells = []
        for bn in ("bfcl", "when2call"):
            tt = [k for k in test if bench[k] == bn]
            cells.append(f"{base[tt].mean():.3f} → {acc[t, tt].mean():.3f} (n={len(tt)})")
        J["fixed_split"][f"{llm}/{dm}"] = {"tau": float(GRID[t]), "cells": cells}
        L.append(f"| {llm} + {dm} | {GRID[t]:.2f} | {cells[0]} | {cells[1]} |")

