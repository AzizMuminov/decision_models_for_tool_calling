"""Re-analyses requested in review, computed only from logged result rows (no new model calls).

  1. Paired effect sizes: discordant counts, paired differences with bootstrap CIs (Studies 2 and 5).
  2. Study 3 with trajectory-clustered bootstrap, per-class recall, DM top-2 accuracy.
  3. Judge sensitivity for Study 1 When2Call (needs scripts/rejudge_when2call.py output).
  4. The held-out tau protocol, scripted, under both judges; a learning curve over dev-set size.
  5. Provider errors left in the final result files, per model.

    .venv/bin/python scripts/review_analyses.py          # -> results/review/REVIEW_ANALYSES.md, review_numbers.json
"""

