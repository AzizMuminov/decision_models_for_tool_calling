for (a, b), r, q in zip(comps, res5, holm([r["p"] for r in res5])):
    r["holm"] = q
    L.append(f"| {a} vs {b} | {fmt(r)} | {q:.2g} |")
J["study5"] = {f"{a}_vs_{b}": r for (a, b), r in zip(comps, res5)}
# the coincident MiMo / DeepSeek score
A, Bm = S5[("MiMo", "full")], S5[("DeepSeek", "full")]
ids = sorted(set(A) & set(Bm))
r = paired([A[i] for i in ids], [Bm[i] for i in ids])
J["study5"]["MiMo_vs_DeepSeek"] = r
L.append(f"| MiMo vs DeepSeek (not pre-registered) | {fmt(r)} | – |")
diff_resp = {k: sum(called5[("MiMo", k)][i] != called5[("DeepSeek", k)][i] for i in keep) for k in ("full", "family+25")}
diff_corr = {k: sum(S5[("MiMo", k)][i] != S5[("DeepSeek", k)][i] for i in keep) for k in ("full", "family+25")}
J["study5"]["mimo_deepseek_differ"] = {"responses": diff_resp, "correctness": diff_corr, "items_per_holster": len(keep)}
L += ["", f"MiMo and DeepSeek on the {len(keep)} analysed items: different tool sets (or a text reply vs a call) on "
      f"{diff_resp['full']} (full) and {diff_resp['family+25']} (family+25) items, i.e. {sum(diff_resp.values())} of "
      f"{2 * len(keep)} responses; correctness differs on {diff_corr['full']} / {diff_corr['family+25']} items.", ""]

# ---------------------------------------------------------------- 2. Study 3, clustered
W = ROOT / "results/swe_replay_v1"
S3: dict = {}
probs3: dict = {}
for name, f, cond in (("Always bash", "baselines", "always_bash"), ("Repeat previous", "baselines", "repeat_prev"),
                      ("Jev", "dm_choice__jev", None), ("MSD1", "dm_choice__msd1", None),
                      ("Sonnet 5.5", "llm_native__sonnet", None), ("DeepSeek", "llm_native__deepseek", None)):
    d = {}
    for r in rows(W / f"{f}.jsonl"):
        if cond and r["condition"] != cond:
            continue
        d[r["id"]] = r
    S3[name] = d
ids3 = sorted(set.intersection(*(set(v) for v in S3.values())))
traj = sorted({i.split("@")[0] for i in ids3})
by_traj = defaultdict(list)
for k, i in enumerate(ids3):
    by_traj[i.split("@")[0]].append(k)
rng = np.random.default_rng(0)
draws = [np.concatenate([by_traj[traj[t]] for t in rng.integers(0, len(traj), len(traj))]) for _ in range(B)]
corr3 = {n: np.array([S3[n][i]["gold"] == S3[n][i]["pred"] for i in ids3], float) for n in S3}


def cl_ci(x: np.ndarray) -> tuple[float, float]:
    m = [x[d].mean() for d in draws]
    return float(np.quantile(m, 0.025)), float(np.quantile(m, 0.975))


L += ["## 2. Study 3 with trajectory-clustered bootstrap", "",
      f"{len(ids3)} steps from {len(traj)} trajectories; the bootstrap resamples whole trajectories.", "",
      "| system | agreement | 95% CI (clustered) | 95% CI (steps, as in v1) | top-2 (DMs) | predicts finish | of which agent finished |",
      "|---|---|---|---|---|---|---|"]
J["study3"] = {}
gold = [S3["Jev"][i]["gold"] for i in ids3]
for n, x in corr3.items():
    lo, hi = cl_ci(x)
    m = [x[rng.integers(0, len(x), len(x))].mean() for _ in range(B)]
    top2 = "–"
    if n in ("Jev", "MSD1"):
        t2 = np.mean([S3[n][i]["gold"] in sorted(S3[n][i]["probs"], key=S3[n][i]["probs"].get)[-2:] for i in ids3])
        top2 = f"{t2:.3f}"
    pf = sum(S3[n][i]["pred"] == "finish" for i in ids3)
    tf = sum(S3[n][i]["pred"] == "finish" and S3[n][i]["gold"] == "finish" for i in ids3)
    J["study3"][n] = {"acc": float(x.mean()), "lo": lo, "hi": hi, "top2": top2, "pred_finish": pf, "true_finish": tf}
    L.append(f"| {n} | {x.mean():.3f} | {lo:.3f}–{hi:.3f} | {np.quantile(m, .025):.3f}–{np.quantile(m, .975):.3f} | {top2} | {pf} | {tf} |")
L += ["", f"Gold `finish` steps: {sum(g == 'finish' for g in gold)}.", "", "Paired differences (clustered bootstrap CI):", "",
      "| A vs B | A−B, pts [95% CI] |", "|---|---|"]
for a, b in (("Jev", "Always bash"), ("Jev", "Sonnet 5.5"), ("Jev", "DeepSeek"), ("Sonnet 5.5", "Always bash"),
             ("MSD1", "Always bash")):
    d = corr3[a] - corr3[b]
    lo, hi = cl_ci(d)
    J["study3"][f"{a}_vs_{b}"] = {"diff": float(d.mean()), "lo": lo, "hi": hi}
    L.append(f"| {a} vs {b} | {100 * d.mean():+.1f} [{100 * lo:+.1f}, {100 * hi:+.1f}] |")
classes = sorted(Counter(gold), key=lambda c: -Counter(gold)[c])
L += ["", "Per-class recall (rows: gold action; n = gold count):", "",
      "| gold action | n | " + " | ".join(n for n in S3 if n not in ("Always bash", "Repeat previous")) + " |",
      "|---|---|" + "---|" * 4]
J["study3"]["recall"] = {}
for c in classes:
    idx = [k for k, g in enumerate(gold) if g == c]
    rec = {n: float(np.mean([S3[n][ids3[k]]["pred"] == c for k in idx])) for n in ("Jev", "MSD1", "Sonnet 5.5", "DeepSeek")}
    J["study3"]["recall"][c] = {"n": len(idx), **rec}
    L.append(f"| `{c}` | {len(idx)} | " + " | ".join(f"{v:.2f}" for v in rec.values()) + " |")
for n in ("Jev", "MSD1", "Sonnet 5.5", "DeepSeek"):
    cm = Counter((S3[n][i]["gold"], S3[n][i]["pred"]) for i in ids3)
    L += ["", f"Confusion counts, {n} (gold → predicted, nonzero off-diagonal, top 8):", ""]
